// 快评.js —— 第一阶段（2026-11-26）：不调模型的廉价预筛
//
// 为什么要它：旧版每轮结束都调一次判定模型，一次请求就是「一整套 system 提示 + 最近 6 轮 + 这一轮」，
// 而「嗯」「好的」「继续」这种纯事务性轮次占了不少，判出来也只是低置信的空转。
// 这里先用一张词表 + 句型白名单过一遍：**只拦「一眼就是事务性」的轮次**，其余照旧交给模型。
//
// 借鉴自 dsh-emotion（中文情感词典快评 + 强信号才触发 LLM 复核）与 dsh-emotion-feedback
// （关键词命中即 0 次模型调用），但有一处有意的不同：那两家用词典**代替**判定；
// 我们只让它决定「要不要判」，判还是模型判 —— 情绪是关系里的细活，词表只够排除「没什么可判」。
//
// 设计上宁可漏放：只要有一点信号（哪怕一个「盯」），就照旧调模型。

export const 词表 = {
  // 负向：难受、被冷落、被凶
  负向: ['难过', '伤心', '想哭', '哭了', '烦', '烦死', '生气', '气死', '讨厌', '恶心', '滚', '凶',
    '骂', '委屈', '失望', '舍不得', '孤单', '冷落', '忽略', '不理', '丢下', '不要我', '骗', '敷衍',
    '心累', '难受', '疼', '崩了', '撑不住', '好累', '累', '困', '无语', '服了', '嫌弃', '唉', '啧', '麻了',
    '傻', '蠢', '笨', '拉黑', '吵', '闹', '憋', '没意思', '算了', '随你'],
  // 正向：被在意、被夸、被黏
  正向: ['喜欢', '爱你', '想你', '抱抱', '抱', '亲', 'mua', '谢谢', '多谢', '辛苦', '棒', '厉害',
    '好耶', '太好', '可爱', '摸摸', '乖', '赞', '牛', '不错', '真好', '开心', '高兴', '稀罕',
    '嘿嘿', '哈哈', '笑死', 'awsl', '好美', '真好看', '好香'],
  // 关系性事件：道歉、承诺、离开、在乎
  关系: ['对不起', '抱歉', '道歉', '陪你', '走了', '别走', '分开', '一个人', '承诺', '答应',
    '原谅', '在乎', '在意', '记得', '忘了', '等你', '回来'],
  // 质疑 / 反讽线索：这类几乎一定要模型看一眼
  质疑: ['盯', '呃', 'Emmm', 'Hmmm', '额', '呵呵', '是吗', '是吧', '你说呢', '不会吧', '真的假的',
    '就这', '我怀疑', '啧'],
}

// 纯应答：整句只有这些词 + 标点，才算事务性
const 纯应答 = /^(?:好|好的|好滴|好嘞|好吧|嗯+|哦+|噢+|喔|ok|okay|行|行吧|可以|对|对的|是|是的|没问题|收到|谢谢|谢了|继续|然后呢?|下一步|再来|没了|不用了?|不必|算了|拜拜|晚安|早安|早|在吗|在不在|哈哈+|hh+|666|👌|👍)[\s。！？!?~…，,、.]*$/i
// 表情包 / 图片 / 语音 / 视频 的标记（QQ 侧会写成 [表情「[动画表情]」已存：D:\…]，带一层嵌套）
const 媒体标记 = /\[[^[\]]*(?:\[[^\]]*\][^[\]]*)*\]/g

/**
 * 看这一轮有没有值得让模型判的东西。
 * **两边都要看**：2026-11-26 岁岁指出「表情包也是情绪表达」——判定模型拿不到图，
 * 只拿到 `[表情「[动画表情]」已存：…]` 这种没有语义的文本；真正的情绪证据在**她自己那轮的反应**里
 * （「awsl」「好可爱」）。所以只跳「两边都没话说」的轮次，媒体轮不再无条件跳。
 * @returns {{强信号: boolean, 命中: object, 事务: boolean, 纯媒体: boolean, 长度: number, 净: string}}
 */
export function 快评(用户 = '', 我 = '') {
  const 我文 = String(我 || '')
  const 文 = String(用户 || '')
  // 信号在两边都算：她说的话和她自己的反应
  const 全文 = 文 + '\n' + 我文
  const 命中 = {}
  for (const [类, 词们] of Object.entries(词表)) {
    const 中 = 词们.filter((w) => 全文.includes(w))
    if (中.length) 命中[类] = 中.slice(0, 6)
  }
  const 强信号 = Object.keys(命中).length > 0
  const 净 = 文.replace(媒体标记, '').replace(/\s+/g, '')
  const 我净 = 我文.replace(媒体标记, '').replace(/\s+/g, '')
  // 纯媒体：她发的是图/表情，而且她自己也没说什么（≤12 字）。她自己说了「awsl」就不算纯媒体了。
  const 纯媒体 = 净.length === 0 && 文.trim().length > 0 && 我净.length <= 12
  // 只认「整句就是一句应答」和「纯媒体」，**而且她自己那轮也没说什么**。
  // 2026-11-26 试算抓到反例：`OK [图片]` 她回了「尾巴卷成…」——光看对方那句会把她自己的反应跳掉。
  // 以前还有一条「短句 + 没信号就算事务」，它把「不要说一和二了……像报告」也跳了（关系性反馈），已删。
  const 事务 = (纯应答.test(净) || 纯媒体) && 我净.length <= 12
  return { 强信号, 命中, 事务, 纯媒体, 长度: 净.length, 我长度: 我净.length, 净 }
}

/**
 * 该不该跳过这一轮的模型判定。
 * 只有「没有信号 + 事务性 + 这轮没跑工具 + 没连着跳太多次」四条同时成立才跳。
 */
export function 该跳吗(评 = {}, 参 = {}) {
  if (参.有工具) return { 跳: false, 理由: '' }
  if (评.强信号) return { 跳: false, 理由: '' }
  if (参.重复) return { 跳: true, 理由: '同一句话刚判过' }
  if (!评.事务) return { 跳: false, 理由: '' }
  const 上限 = Number.isFinite(Number(参.上限)) ? Math.max(0, Number(参.上限)) : 3
  if ((Number(参.连续跳过) || 0) >= 上限) return { 跳: false, 理由: '' }
  return { 跳: true, 理由: 评.纯媒体 ? '她只发了图/表情，自己也没吭声' : '纯应答，没有情绪信号' }
}
